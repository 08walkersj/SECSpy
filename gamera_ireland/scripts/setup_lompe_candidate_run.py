#!/usr/bin/env python3
"""Create a parameterized LOMPE-like public MAGE/GAMERA candidate run."""

from __future__ import annotations

import argparse
import json
import os
import shutil
import sys
from pathlib import Path

import h5py
import numpy as np
import pandas as pd
from astropy.time import Time

SCRIPT_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(SCRIPT_DIR))

from setup_lompe_pressure_pulse import (  # noqa: E402
    DEFAULT_RUN_DIR,
    KAIJU_DIR,
    KAIPY_PREPROC,
    MAGEPY_ENV,
    MAGEPY_PYTHON,
    PROJECT_DIR,
    check_preprocessing_tools,
    run_command,
    write_calcdb_xml,
    write_xml,
)


def smooth_box(t_s: np.ndarray, start_s: float, end_s: float, width_s: float) -> np.ndarray:
    rise = 0.5 * (1.0 + np.tanh((t_s - start_s) / width_s))
    fall = 0.5 * (1.0 + np.tanh((t_s - end_s) / width_s))
    return rise - fall


def write_bcwind(path: Path, args: argparse.Namespace) -> dict:
    start = pd.Timestamp(args.start)
    t_s = np.arange(0.0, args.duration_s + args.cadence_s, args.cadence_s)
    pulse = smooth_box(t_s, args.pulse_start_s, args.pulse_end_s, args.pulse_width_s)
    recovery = smooth_box(t_s, args.recovery_start_s, args.recovery_end_s, args.pulse_width_s)

    density = args.density_base + args.density_delta * pulse
    temp = np.full(t_s.size, args.temperature_k)
    vx = np.full(t_s.size, args.vx_kms * 1.0e3)
    vy = np.full(t_s.size, args.vy_kms * 1.0e3)
    vz = np.full(t_s.size, args.vz_kms * 1.0e3)
    bx = np.full(t_s.size, args.bx_nt)
    by = np.full(t_s.size, args.by_nt)
    bz = np.full(t_s.size, args.bz_south_nt)
    if args.bz_recovery_nt is not None:
        bz = bz * (1.0 - recovery) + args.bz_recovery_nt * recovery

    f107 = np.full(t_s.size, args.f107)
    kp = np.full(t_s.size, args.kp)
    symh = np.full(t_s.size, args.symh)
    zeros = np.zeros(t_s.size)
    mjd0 = Time(start.to_pydatetime()).mjd
    mjd = mjd0 + t_s / 86400.0
    ut = np.asarray([(start + pd.Timedelta(seconds=float(t))).isoformat().encode("utf-8") for t in t_s])

    with h5py.File(path, "w") as handle:
        handle.attrs["source"] = "Parameterized LOMPE-like synthetic driver"
        handle.attrs["start_utc"] = start.isoformat()
        handle.attrs["description"] = "Generated by setup_lompe_candidate_run.py"
        for name, values in {
            "T": t_s,
            "UT": ut,
            "MJD": mjd,
            "D": density,
            "Temp": temp,
            "Vx": vx,
            "Vy": vy,
            "Vz": vz,
            "Bx": bx,
            "By": by,
            "Bz": bz,
            "tilt": zeros,
            "ae": zeros,
            "al": zeros,
            "au": zeros,
            "symh": symh,
            "Interped": np.zeros(t_s.size, dtype=np.int8),
            "f10.7": f107,
            "Kp": kp,
        }.items():
            handle.create_dataset(name, data=values)
        handle.create_dataset("Bx0", data=args.bx0)
        handle.create_dataset("ByC", data=args.byc)
        handle.create_dataset("BzC", data=args.bzc)

    pdyn = 1.6726219e-6 * density * abs(args.vx_kms) ** 2
    return {
        "start_utc": start.isoformat(),
        "time_s_min_max": [float(t_s.min()), float(t_s.max())],
        "density_cm3_min_max": [float(density.min()), float(density.max())],
        "vx_kms": args.vx_kms,
        "by_nt": args.by_nt,
        "bz_nt_min_max": [float(bz.min()), float(bz.max())],
        "dynamic_pressure_npa_min_max": [float(pdyn.min()), float(pdyn.max())],
        "pulse_start_end_s": [args.pulse_start_s, args.pulse_end_s],
    }


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run-dir", type=Path, default=DEFAULT_RUN_DIR.parent / "lompe_candidate")
    parser.add_argument("--runid", default="lompe_candidate")
    parser.add_argument("--clobber", action="store_true")
    parser.add_argument("--start", default="1998-04-23T18:00:00")
    parser.add_argument("--duration-s", type=float, default=300.0)
    parser.add_argument("--spinup-s", type=float, default=60.0)
    parser.add_argument("--dtout-s", type=float, default=60.0)
    parser.add_argument("--cadence-s", type=float, default=30.0)
    parser.add_argument("--density-base", type=float, default=5.0)
    parser.add_argument("--density-delta", type=float, default=35.0)
    parser.add_argument("--pulse-start-s", type=float, default=-60.0)
    parser.add_argument("--pulse-end-s", type=float, default=900.0)
    parser.add_argument("--pulse-width-s", type=float, default=30.0)
    parser.add_argument("--vx-kms", type=float, default=-450.0)
    parser.add_argument("--vy-kms", type=float, default=0.0)
    parser.add_argument("--vz-kms", type=float, default=0.0)
    parser.add_argument("--bx-nt", type=float, default=0.0)
    parser.add_argument("--by-nt", type=float, default=0.0)
    parser.add_argument("--bz-south-nt", type=float, default=-10.0)
    parser.add_argument("--bz-recovery-nt", type=float)
    parser.add_argument("--recovery-start-s", type=float, default=1.0e9)
    parser.add_argument("--recovery-end-s", type=float, default=1.0e9)
    parser.add_argument("--temperature-k", type=float, default=1.0e5)
    parser.add_argument("--f107", type=float, default=120.0)
    parser.add_argument("--kp", type=float, default=4.0)
    parser.add_argument("--symh", type=float, default=0.0)
    parser.add_argument("--bx0", type=float, default=0.0)
    parser.add_argument("--byc", type=float, default=0.0)
    parser.add_argument("--bzc", type=float, default=0.0)
    parser.add_argument(
        "--remix-low-lat-boundary",
        type=float,
        default=45.0,
        help="Equatorward ReMIX colatitude boundary in degrees. The public LOMPE sample reaches about 45 MLAT.",
    )
    parser.add_argument("--remix-np", type=int, default=360)
    parser.add_argument("--remix-nt", type=int, default=45)
    parser.add_argument("--ri", type=int, default=1, help="GAMERA MPI decomposition in i.")
    parser.add_argument("--rj", type=int, default=1, help="GAMERA MPI decomposition in j.")
    parser.add_argument("--rk", type=int, default=1, help="GAMERA MPI decomposition in k.")
    parser.add_argument(
        "--restart-dt-s",
        type=float,
        help="Restart cadence in seconds. Defaults to one restart after the requested final time.",
    )
    parser.add_argument(
        "--no-raiju",
        action="store_true",
        help="Use Kaiju's shallow GAMERA+ReMIX coupling path instead of deep RAIJU coupling.",
    )
    parser.add_argument("--do-starlight", action="store_true")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    if args.run_dir.exists() and args.clobber:
        shutil.rmtree(args.run_dir)
    args.run_dir.mkdir(parents=True, exist_ok=True)
    check_preprocessing_tools()

    env = os.environ.copy()
    env["KAIJUHOME"] = str(KAIJU_DIR)
    env.setdefault("MPLCONFIGDIR", str(PROJECT_DIR / "environment" / "matplotlib"))
    env.setdefault("SPACEPY", str(PROJECT_DIR / "environment" / "spacepy"))

    run_command([str(MAGEPY_PYTHON), str(KAIPY_PREPROC / "genLFM.py"), "-gid", "D"], args.run_dir, env)
    if not args.no_raiju:
        run_command([str(MAGEPY_PYTHON), str(KAIPY_PREPROC / "genRAIJU.py"), "-o", "raijuconfig.h5"], args.run_dir, env)

    bcwind = write_bcwind(args.run_dir / "bcwind.h5", args)
    xml = write_xml(
        args.run_dir,
        args.runid,
        args.duration_s,
        args.spinup_s,
        args.dtout_s,
        args.remix_low_lat_boundary,
        args.remix_np,
        args.remix_nt,
        args.do_starlight,
        args.ri,
        args.rj,
        args.rk,
        args.restart_dt_s,
        not args.no_raiju,
    )
    calcdb_xml = write_calcdb_xml(args.run_dir, args.runid, args.duration_s, args.dtout_s)

    manifest = {
        "purpose": "Parameterized public MAGE/GAMERA candidate for matching the LOMPE synthetic data class",
        "runid": args.runid,
        "run_dir": str(args.run_dir),
        "bcwind": bcwind,
        "remix_grid": {
            "LowLatBoundary_colat_deg": args.remix_low_lat_boundary,
            "equatorward_mlat_deg": 90.0 - args.remix_low_lat_boundary,
            "Np": args.remix_np,
            "Nt": args.remix_nt,
        },
        "conductance": {
            "doStarlight": args.do_starlight,
        },
        "coupling": {
            "doDeep": not args.no_raiju,
            "imType": "RAIJU" if not args.no_raiju else None,
        },
        "mpi_decomposition": {
            "Ri": args.ri,
            "Rj": args.rj,
            "Rk": args.rk,
            "required_mpi_ranks": args.ri * args.rj * args.rk + 1,
        },
        "restart_dt_s": args.restart_dt_s,
        "xml": xml.name,
        "calcdb_xml": calcdb_xml.name,
        "commands": {
            "voltron": f"env KAIJUHOME={KAIJU_DIR} conda run -n SECSpy {KAIJU_DIR / 'build_serial/bin/voltron.x'} {xml.name}",
            "voltron_mpi": f"env KAIJUHOME={KAIJU_DIR} conda run -n SECSpy mpirun -np {args.ri * args.rj * args.rk + 1} {KAIJU_DIR / 'build_mpi/bin/voltron_mpi.x'} {xml.name}",
            "calcdb": f"conda run -n SECSpy {KAIJU_DIR / 'build_serial/bin/calcdb.x'} {calcdb_xml.name}",
        },
    }
    (args.run_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps(manifest, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
