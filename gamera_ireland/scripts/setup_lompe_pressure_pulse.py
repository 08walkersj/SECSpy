#!/usr/bin/env python3
"""Create a from-scratch GAMERA pressure-pulse case matching the LOMPE test class.

The LOMPE paper's original GAMERA input deck is not distributed with the LOMPE
repository. This script creates a transparent, reproducible pressure-pulse
GAMERA/ReMIX/RAIJU case using the public Kaiju/KaiPy tools and the solar-wind
HDF5 format documented by Kaiju.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

import h5py
import numpy as np
import pandas as pd
from astropy.time import Time


PROJECT_DIR = Path(__file__).resolve().parents[1]
REPO_DIR = PROJECT_DIR.parent
DEFAULT_RUN_DIR = PROJECT_DIR / "simulations" / "lompe_pressure_pulse"
MAGEPY_ENV = Path("/home/simon/anaconda3/envs/MAGEPy312")
MAGEPY_PYTHON = MAGEPY_ENV / "bin" / "python"
KAIPY_PREPROC = MAGEPY_ENV / "lib/python3.12/site-packages/kaipy/scripts/preproc"
KAIJU_DIR = PROJECT_DIR / "external" / "kaiju-master"


def run_command(args: list[str], cwd: Path, env: dict[str, str]) -> None:
    print("+ " + " ".join(args))
    subprocess.run(args, cwd=cwd, env=env, check=True)


def check_preprocessing_tools() -> None:
    required = [
        MAGEPY_PYTHON,
        KAIPY_PREPROC / "genLFM.py",
        KAIPY_PREPROC / "genRAIJU.py",
        MAGEPY_ENV / "lib/python3.12/site-packages/kaipy/gamera/lfmG.X.txt",
        MAGEPY_ENV / "lib/python3.12/site-packages/kaipy/gamera/lfmG.Y.txt",
    ]
    missing = [path for path in required if not path.exists()]
    if missing:
        missing_text = "\n".join(str(path) for path in missing)
        raise FileNotFoundError(f"Missing MAGE preprocessing files:\n{missing_text}")


def write_pressure_pulse_bcwind(path: Path) -> dict:
    """Write a deterministic pressure-pulse solar wind file for GAMERA."""
    start = pd.Timestamp("1998-04-23T18:00:00")
    duration_hours = 5.0
    cadence_s = 60.0
    t_s = np.arange(0.0, duration_hours * 3600.0 + cadence_s, cadence_s)
    t_h = t_s / 3600.0
    n = np.full(t_s.size, 5.0)
    temp = np.full(t_s.size, 1.0e5)
    vx = np.full(t_s.size, -400.0e3)
    vy = np.zeros(t_s.size)
    vz = np.zeros(t_s.size)
    bx = np.zeros(t_s.size)
    by = np.zeros(t_s.size)
    bz = np.full(t_s.size, -5.0)
    f107 = np.full(t_s.size, 100.0)
    kp = np.full(t_s.size, 3.0)
    symh = np.zeros(t_s.size)
    ae = np.zeros(t_s.size)
    al = np.zeros(t_s.size)
    au = np.zeros(t_s.size)
    interped = np.zeros(t_s.size, dtype=np.int8)

    # Smooth density pulse: dynamic pressure rises from about 1.3 nPa to
    # about 6.4 nPa, then relaxes. This is the synthetic driver.
    rise = 0.5 * (1.0 + np.tanh((t_h - 1.0) / 0.08))
    fall = 0.5 * (1.0 + np.tanh((t_h - 2.25) / 0.12))
    pulse = rise - fall
    n += 20.0 * pulse

    # Add a weaker northward recovery interval so the system relaxes.
    bz = np.where((t_h >= 3.0) & (t_h <= 4.2), 5.0, bz)

    mjd0 = Time(start.to_pydatetime()).mjd
    mjd = mjd0 + t_s / 86400.0
    ut = np.asarray([(start + pd.Timedelta(seconds=float(t))).isoformat().encode("utf-8") for t in t_s])

    with h5py.File(path, "w") as h:
        h.attrs["source"] = "Synthetic pressure-pulse boundary condition generated by setup_lompe_pressure_pulse.py"
        h.attrs["start_utc"] = start.isoformat()
        h.attrs["description"] = "LOMPE-like GAMERA synthetic pressure increase, not the original unpublished LOMPE deck"
        h.create_dataset("T", data=t_s)
        h.create_dataset("UT", data=ut)
        h.create_dataset("MJD", data=mjd)
        h.create_dataset("D", data=n)
        h.create_dataset("Temp", data=temp)
        h.create_dataset("Vx", data=vx)
        h.create_dataset("Vy", data=vy)
        h.create_dataset("Vz", data=vz)
        h.create_dataset("Bx", data=bx)
        h.create_dataset("By", data=by)
        h.create_dataset("Bz", data=bz)
        h.create_dataset("tilt", data=np.zeros(t_s.size))
        h.create_dataset("ae", data=ae)
        h.create_dataset("al", data=al)
        h.create_dataset("au", data=au)
        h.create_dataset("symh", data=symh)
        h.create_dataset("Interped", data=interped)
        h.create_dataset("f10.7", data=f107)
        h.create_dataset("Kp", data=kp)
        h.create_dataset("Bx0", data=0.0)
        h.create_dataset("ByC", data=0.0)
        h.create_dataset("BzC", data=0.0)

    p_dyn = 1.6726219e-6 * n * (np.abs(vx) / 1.0e3) ** 2
    return {
        "start_utc": start.isoformat(),
        "cadence_s": cadence_s,
        "duration_hours": duration_hours,
        "density_cm3_min_max": [float(n.min()), float(n.max())],
        "vx_ms": float(vx[0]),
        "bz_nt_values": sorted(set(float(v) for v in bz)),
        "dynamic_pressure_npa_min_max": [float(p_dyn.min()), float(p_dyn.max())],
    }


def write_xml(
    run_dir: Path,
    runid: str,
    tfin: float,
    tspin: float,
    dtout: float,
    remix_low_lat_boundary: float,
    remix_np: int,
    remix_nt: int,
    do_starlight: bool,
    ri: int = 1,
    rj: int = 1,
    rk: int = 1,
    restart_dt: float | None = None,
    do_raiju: bool = True,
) -> Path:
    starlight = "T" if do_starlight else "F"
    restart_dt = restart_dt if restart_dt is not None else tfin + dtout + 1.0
    chimp_block = ""
    raiju_block = ""
    coupling = '<coupling doGCM="F" dtCouple="5.0" doDeep="F" doAsyncCoupling="F" />'
    precipitation = '<precipitation aurora_model_type="FEDDER" beta="0.2" doAuroralSmooth="F" />'
    if do_raiju:
        coupling = (
            '<coupling doGCM="F" dtCouple="5.0" doDeep="T" imType="RAIJU" '
            'doQkSquish="T" qkSquishStride="2" doAsyncCoupling="F" />'
        )
        precipitation = '<precipitation aurora_model_type="LINMRG" beta="0.2" doAuroralSmooth="F" />'
        chimp_block = """  <CHIMP>
    <units uid="EARTHCODE" />
    <fields grType="lfm" />
    <domain dtype="MAGE" />
    <tracer epsds="0.05" />
  </CHIMP>
"""
        raiju_block = """  <RAIJU>
    <output loudConsole="F" />
    <grid gType="SHGRID" ThetaL="15" />
    <domain tail_buffer="15.0" sun_buffer="15.0" tail_active="12.0" sun_active="12.0" />
    <config fname="raijuconfig.h5" />
    <plasmasphere doPsphere="T" doExcessMap="T" />
    <losses doLosses="T" doCX="T" doCC="T" doEWM="T" ewmType="SS" />
    <cpl nFluidsIn="1" startupTscl="7200.0" />
    <fluidIn1 imhd="0" flav="2" excessToPsph="T" />
  </RAIJU>
"""
    text = f"""<Kaiju>
  <Gamera>
    <sim runid="{runid}" doH5g="T" H5Grid="lfmD.h5" icType="user" pdmb="0.75" rmeth="8C" />
    <floors dFloor="1.0e-4" pFloor="1.0e-6" />
    <timestep doCPR="T" limCPR="0.20" />
    <restart doRes="F" resID="{runid}" nRes="-1" />
    <physics doMHD="T" doBoris="T" Ca="20.0" />
    <ring gid="lfm" doRing="T" />
    <wind tsfile="bcwind.h5" />
    <source doSource="T" doWolfLim="T" doBounceDT="T" nBounce="1.0" />
    <iPdir N="{ri}" bcPeriodic="F" />
    <jPdir N="{rj}" bcPeriodic="F" />
    <kPdir N="{rk}" bcPeriodic="T" />
    <coupling blockHalo="F" />
  </Gamera>
{chimp_block}  <VOLTRON>
    <time tFin="{tfin:.1f}" />
    <spinup doSpin="T" tSpin="{tspin:.1f}" />
    <output dtOut="{dtout:.1f}" dtCon="30.0" />
    {coupling}
    <restart dtRes="{restart_dt:.1f}" />
    <imag doInit="T" />
    <helpers numHelpers="0" useHelpers="F" doSquishHelp="F" />
  </VOLTRON>
  <REMIX>
    <grid Np="{remix_np}" Nt="{remix_nt}" LowLatBoundary="{remix_low_lat_boundary:.1f}" />
    <conductance doStarlight="{starlight}" apply_cap="T" const_sigma="F" />
    {precipitation}
  </REMIX>
{raiju_block}
</Kaiju>
"""
    path = run_dir / f"{runid}.xml"
    path.write_text(text)
    return path


def write_calcdb_xml(run_dir: Path, runid: str, tfin: float, dt: float) -> Path:
    text = f"""<?xml version="1.0"?>
<Kaiju>
  <Chimp>
    <sim runid="{runid}"/>
    <time T0="0.0" dt="{dt:.1f}" tFin="{tfin:.1f}"/>
    <fields ebfile="{runid}" grType="LFM" doJ="T" isMPI="false"/>
    <parallel Ri="1" Rj="1" Rk="1"/>
    <grid Nlat="181" Nlon="361" Nz="1"/>
  </Chimp>
</Kaiju>
"""
    path = run_dir / f"calcdb_{runid}.xml"
    path.write_text(text)
    return path


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run-dir", type=Path, default=DEFAULT_RUN_DIR)
    parser.add_argument("--clobber", action="store_true")
    parser.add_argument(
        "--remix-low-lat-boundary",
        type=float,
        default=60.0,
        help="Equatorward ReMIX colatitude boundary in degrees; 60 gives a grid down to 30 MLAT.",
    )
    parser.add_argument("--remix-np", type=int, default=360, help="Number of ReMIX longitude/MLT cells.")
    parser.add_argument("--remix-nt", type=int, default=61, help="Number of ReMIX colatitude points including the pole.")
    parser.add_argument("--ri", type=int, default=1, help="GAMERA MPI decomposition in i.")
    parser.add_argument("--rj", type=int, default=1, help="GAMERA MPI decomposition in j.")
    parser.add_argument("--rk", type=int, default=1, help="GAMERA MPI decomposition in k.")
    parser.add_argument(
        "--restart-dt-s",
        type=float,
        help="Restart cadence in seconds. Defaults to one restart after the requested final time.",
    )
    parser.add_argument(
        "--do-starlight",
        action="store_true",
        help="Enable ReMIX starlight conductance smoothing. Default is off for electrojet diagnostics.",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    run_dir = args.run_dir
    if run_dir.exists() and args.clobber:
        shutil.rmtree(run_dir)
    run_dir.mkdir(parents=True, exist_ok=True)
    check_preprocessing_tools()

    env = os.environ.copy()
    env["KAIJUHOME"] = str(KAIJU_DIR)
    env.setdefault("MPLCONFIGDIR", str(PROJECT_DIR / "environment" / "matplotlib"))
    env.setdefault("SPACEPY", str(PROJECT_DIR / "environment" / "spacepy"))

    run_command(
        [str(MAGEPY_PYTHON), str(KAIPY_PREPROC / "genLFM.py"), "-gid", "D"],
        run_dir,
        env,
    )
    run_command(
        [str(MAGEPY_PYTHON), str(KAIPY_PREPROC / "genRAIJU.py"), "-o", "raijuconfig.h5"],
        run_dir,
        env,
    )
    bcwind_summary = write_pressure_pulse_bcwind(run_dir / "bcwind.h5")

    production_xml = write_xml(
        run_dir,
        runid="lompe_pressure_pulse",
        tfin=5.0 * 3600.0,
        tspin=3600.0,
        dtout=300.0,
        remix_low_lat_boundary=args.remix_low_lat_boundary,
        remix_np=args.remix_np,
        remix_nt=args.remix_nt,
        do_starlight=args.do_starlight,
        ri=args.ri,
        rj=args.rj,
        rk=args.rk,
        restart_dt=args.restart_dt_s,
    )
    smoke_xml = write_xml(
        run_dir,
        runid="lompe_pressure_pulse_smoke",
        tfin=120.0,
        tspin=60.0,
        dtout=60.0,
        remix_low_lat_boundary=args.remix_low_lat_boundary,
        remix_np=args.remix_np,
        remix_nt=args.remix_nt,
        do_starlight=args.do_starlight,
        ri=args.ri,
        rj=args.rj,
        rk=args.rk,
        restart_dt=args.restart_dt_s,
    )
    calcdb_xml = write_calcdb_xml(run_dir, "lompe_pressure_pulse", 5.0 * 3600.0, 300.0)
    calcdb_smoke_xml = write_calcdb_xml(run_dir, "lompe_pressure_pulse_smoke", 120.0, 60.0)

    manifest = {
        "purpose": "From-scratch GAMERA/ReMIX/RAIJU pressure-pulse case matching the class of the LOMPE synthetic test",
        "not_exact_lompe_paper_deck": True,
        "reason": "The LOMPE repository provides gamera.nc but not the original GAMERA XML/grid/bcwind used to create it.",
        "run_dir": str(run_dir),
        "bcwind": bcwind_summary,
        "remix_grid": {
            "Np": args.remix_np,
            "Nt": args.remix_nt,
            "LowLatBoundary_colat_deg": args.remix_low_lat_boundary,
            "equatorward_mlat_deg": 90.0 - args.remix_low_lat_boundary,
        },
        "conductance": {
            "doStarlight": args.do_starlight,
            "note": "Default is false to avoid starlight-controlled day/night structure dominating signed electrojet diagnostics.",
        },
        "mpi_decomposition": {
            "Ri": args.ri,
            "Rj": args.rj,
            "Rk": args.rk,
            "required_mpi_ranks": args.ri * args.rj * args.rk + 1,
        },
        "files": {
            "preprocessing_environment": str(MAGEPY_ENV),
            "grid": "lfmD.h5",
            "raiju_config": "raijuconfig.h5",
            "bcwind": "bcwind.h5",
            "production_xml": production_xml.name,
            "smoke_xml": smoke_xml.name,
            "production_calcdb_xml": calcdb_xml.name,
            "smoke_calcdb_xml": calcdb_smoke_xml.name,
        },
        "run_commands": {
            "smoke": f"conda run -n SECSpy {KAIJU_DIR / 'build_serial/bin/voltron.x'} {smoke_xml.name}",
            "production": f"conda run -n SECSpy {KAIJU_DIR / 'build_serial/bin/voltron.x'} {production_xml.name}",
            "smoke_mpi": f"conda run -n SECSpy mpirun -np {args.ri * args.rj * args.rk + 1} {KAIJU_DIR / 'build_mpi/bin/voltron_mpi.x'} {smoke_xml.name}",
            "production_mpi": f"conda run -n SECSpy mpirun -np {args.ri * args.rj * args.rk + 1} {KAIJU_DIR / 'build_mpi/bin/voltron_mpi.x'} {production_xml.name}",
            "calcdb_smoke": f"conda run -n SECSpy {KAIJU_DIR / 'build_serial/bin/calcdb.x'} {calcdb_smoke_xml.name}",
            "calcdb_production": f"conda run -n SECSpy {KAIJU_DIR / 'build_serial/bin/calcdb.x'} {calcdb_xml.name}",
        },
    }
    manifest_path = run_dir / "manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"Wrote {manifest_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
